import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

df = pd.read_csv("/content/drive/MyDrive/Colab Notebooks/kc_house_data.csv")

df.head()

df.tail()

df.info()

df.describe()

df.shape

df.columns

df.isnull().sum()

df.duplicated().sum()

df["date"] = pd.to_datetime(
    df["date"].astype(str).str[:8],
    format="%Y%m%d",
    errors="coerce"
)

df["date"].head()

df["sale_year"] = df["date"].dt.year
df["sale_month"] = df["date"].dt.month
df["sale_quarter"] = df["date"].dt.quarter

df[["date", "sale_year", "sale_month", "sale_quarter"]].head()

df.isnull().sum()

print("Zero bedrooms:", (df["bedrooms"] == 0).sum())
print("Zero bathrooms:", (df["bathrooms"] == 0).sum())

df = df[(df["bedrooms"] > 0) & (df["bathrooms"] > 0)]
print("Rows after cleaning:", len(df))

df["property_age"] = df["sale_year"] - df["yr_built"]
df[["sale_year", "yr_built", "property_age"]].head()

df["is_renovated"] = np.where(df["yr_renovated"] > 0, 1, 0)
df[["yr_renovated", "is_renovated"]].head()

df["years_since_renovation"] = np.where(
    df["yr_renovated"] > 0,
    df["sale_year"] - df["yr_renovated"],
    0
)
df[["sale_year", "yr_renovated", "years_since_renovation"]].head()

df["price_per_sqft_living"] = df["price"] / df["sqft_living"]
df["price_per_sqft_lot"] = df["price"] / df["sqft_lot"]
df[[
    "price",
    "sqft_living",
    "sqft_lot",
    "price_per_sqft_living",
    "price_per_sqft_lot"
]].head()

df[["price_per_sqft_living", "price_per_sqft_lot"]].describe()

plt.figure(figsize=(8, 5))
sns.boxplot(x=df["price_per_sqft_living"])
plt.title("Price Per Square Foot - Living Area")
plt.xlabel("Price per Sqft")
plt.show()

plt.figure(figsize=(8, 5))
sns.boxplot(x=df["price_per_sqft_lot"])
plt.title("Price Per Square Foot - Lot Size")
plt.xlabel("Price per Sqft")
plt.show()

Q1 = df["price_per_sqft_living"].quantile(0.25)
Q3 = df["price_per_sqft_living"].quantile(0.75)
IQR = Q3 - Q1

lower_bound = Q1 - 1.5 * IQR
upper_bound = Q3 + 1.5 * IQR

living_outliers = df[
    (df["price_per_sqft_living"] < lower_bound) |
    (df["price_per_sqft_living"] > upper_bound)
]

print("Living Area Price/Sqft")
print("Q1:", Q1)
print("Q3:", Q3)
print("IQR:", IQR)
print("Lower Bound:", lower_bound)
print("Upper Bound:", upper_bound)
print("Number of Outliers:", len(living_outliers))

Q1_lot = df["price_per_sqft_lot"].quantile(0.25)
Q3_lot = df["price_per_sqft_lot"].quantile(0.75)
IQR_lot = Q3_lot - Q1_lot

lower_bound_lot = Q1_lot - 1.5 * IQR_lot
upper_bound_lot = Q3_lot + 1.5 * IQR_lot

lot_outliers = df[
    (df["price_per_sqft_lot"] < lower_bound_lot) |
    (df["price_per_sqft_lot"] > upper_bound_lot)
]

print("Lot Size Price/Sqft")
print("Q1:", Q1_lot)
print("Q3:", Q3_lot)
print("IQR:", IQR_lot)
print("Lower Bound:", lower_bound_lot)
print("Upper Bound:", upper_bound_lot)
print("Number of Outliers:", len(lot_outliers))

